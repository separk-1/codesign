import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true, channel:'msedge'});
try {
 const page = await browser.newPage({viewport:{width:1500,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173');
 await page.getByRole('tab',{name:'Commissioning',exact:true}).click();
 await page.getByRole('heading',{name:'Commissioning workbench'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Approve local draft only'}).isEnabled(),false);
 await page.getByLabel('Reviewer name').fill('Demo reviewer');
 await page.getByLabel('Review notes / open items').fill('Reviewed demonstration; airflow remains unresolved.');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Approve local draft only'}).click();
 await page.getByRole('status').filter({hasText:'Local draft approved:'}).waitFor();
 await page.getByLabel('Observations to collect').fill('Edited synthetic observation plan');
 assert.equal(await page.getByRole('button',{name:'Approve local draft only'}).isEnabled(),false);
 await page.getByRole('button',{name:'02 · Occupancy transition conflict'}).click();
 await page.getByLabel('Reviewer name').fill('Demo reviewer');
 await page.getByLabel('Review notes / open items').fill('Conflict is unresolved');
 await page.getByRole('checkbox').check();
 assert.equal(await page.getByRole('button',{name:'Approve local draft only'}).isEnabled(),false);
 await page.getByLabel('Specification version').selectOption('2020-10-02');
 await page.getByText('VAV sampling: 10%',{exact:false}).waitFor();
 await page.getByRole('button',{name:'03 · High-temperature alarm / observability'}).click();
 await page.getByText('Potential observability gap:',{exact:false}).waitFor();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export drafts JSON'}).click();
 const download=await downloadPromise; const stream=await download.createReadStream(); const chunks=[];
 for await(const chunk of stream) chunks.push(chunk);
 const data=JSON.parse(Buffer.concat(chunks).toString());
 assert.equal(data.fieldStatus,'NOT EXECUTED'); assert.equal(data.certification,false);
 assert.equal(data.drafts[0].approvedAt,''); assert.ok(data.drafts[0].history.some(v=>v.includes('invalidated')));
 await page.reload(); await page.getByRole('tab',{name:'Commissioning',exact:true}).click();
 assert.equal(await page.getByLabel('Observations to collect').inputValue(),'Edited synthetic observation plan');
 assert.equal(await page.getByLabel('Specification version').inputValue(),'2020-10-02');
 await page.screenshot({path:'docs/commissioning-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.screenshot({path:'docs/commissioning-mobile.png',fullPage:true});
 await page.getByRole('tab',{name:'Design',exact:true}).click();
 await page.getByRole('button',{name:'Design basis +',exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS: draft gates, approval invalidation, conflict block, version selection, export, persistence, responsive layout, Design tab, no browser exceptions');
} finally {await browser.close();}

